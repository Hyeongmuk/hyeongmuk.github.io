"""Convert the existing, already public cluster SPT Jupyter notebook into a
readable Astro Markdown note. We do not execute notebook cells; figures absent
from the input notebook cannot be automatically recreated.
"""
from pathlib import Path
import json
import shutil
import zipfile

root = Path(__file__).resolve().parent.parent
original_zip = Path('/mnt/data/hyeongmuk.github.io-main.zip')
existing_notebook = root / 'public/downloads/cluster_spt.ipynb'
if original_zip.exists():
    with zipfile.ZipFile(original_zip) as archive:
        name = next(n for n in archive.namelist() if n.endswith('/cluster_spt.ipynb'))
        existing_notebook.write_bytes(archive.read(name))
if not existing_notebook.exists():
    raise SystemExit('Please first put the original notebook in public/downloads/cluster_spt.ipynb')
notebook = json.loads(existing_notebook.read_text())
frontmatter = '''---
title: 'The 1D Cluster Model as a Symmetry-Protected Topological Phase'
description: 'Stabilizers, edge degeneracy, and symmetry protection in the one-dimensional cluster model.'
date: 2026-08-17
topic: 'SPT phases · Computation'
status: published
pdf: '/downloads/cluster_model_reading_excerpt.pdf'
downloads:
  - label: 'Original Jupyter Notebook'
    href: '/downloads/cluster_spt.ipynb'
  - label: 'Markdown source'
    href: '/downloads/cluster_model_spt.md'
---

> **About this online version.** Converted from the notebook already present in the original GitHub repository. Code cells are displayed but not executed. The original notebook had no saved execution outputs, so figures must be generated by running it locally.

'''
text = [frontmatter]
markdown_only = ["# The 1D Cluster Model as a Symmetry-Protected Topological Phase\n\n", 'This is a reading-only extract of the explanatory cells from the public notebook. For executable code and plots, download the original Jupyter Notebook.\n\n']
for cell in notebook['cells']:
    body = ''.join(cell.get('source', []))
    if cell['cell_type'] == 'markdown':
        text.append(body + '\n\n')
        if not body.startswith('# The 1D Cluster Model'):
            markdown_only.append(body + '\n\n')
    elif cell['cell_type'] == 'code':
        text.append('```python\n' + body.rstrip() + '\n```\n\n')
(root / 'src/content/notes/cluster-model.md').write_text(''.join(text), encoding='utf8')
(root / 'public/downloads/cluster_model_spt.md').write_text(''.join(text).split('---',2)[-1], encoding='utf8')
(root / 'public/downloads/cluster_model_reading_excerpt.md').write_text(''.join(markdown_only), encoding='utf8')
print('Converted',len(notebook['cells']),'notebook cells')
